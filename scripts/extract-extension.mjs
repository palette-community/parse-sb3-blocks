#!/usr/bin/env node
// Extract a Scratch extension JS file into a bundled module under src/extensions
// and register it in src/extensions/index.js, so it can later be loaded with
// `registerBundledExtensions()`.
//
// Usage:
//   node scripts/extract-extension.mjs <path-to-extension.js> [--url <url>] [--out <dir>]
//
// Requires scratch-sandbox (already a dependency) for parsing:
//   npm install github:palette-community/scratch-sandbox

import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, resolve, basename } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseExtension } from 'scratch-sandbox';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, '..');
const EXT_DIR = resolve(ROOT, 'src/extensions');

function parseArgs(argv) {
    const args = { url: undefined, out: EXT_DIR };
    const positional = [];
    for (let i = 0; i < argv.length; i++) {
        const a = argv[i];
        if (a === '--url') args.url = argv[++i];
        else if (a === '--out') args.out = resolve(a);
        else positional.push(a);
    }
    if (positional.length !== 1) {
        console.error('Usage: extract-extension.mjs <extension.js> [--url <url>] [--out <dir>]');
        process.exit(1);
    }
    args.file = resolve(positional[0]);
    return args;
}

function updateIndexFile(outDir, id, moduleName) {
    const indexPath = resolve(outDir, 'index.js');
    let body = '// AUTO-GENERATED extension bundle list.\n' +
        '// Each entry is a `getInfo()` descriptor compiled by `registerExtensionInfo`.\n' +
        '// Populate this list with `node scripts/extract-extension.mjs <ext.js>`.\n';
    const imports = [];
    const ids = [];
    if (existsSync(indexPath)) {
        const prev = readFileSync(indexPath, 'utf8');
        const re = /import\s+(\w+)\s+from\s+'(\.\/[^']+)';/g;
        let m;
        while ((m = re.exec(prev))) {
            imports.push(`import ${m[1]} from '${m[2]}';`);
            ids.push(m[1]);
        }
    }
    const varName = /^[a-zA-Z_$][\w$]*$/.test(id) ? `ext_${id}` : `ext_${ids.length}`;
    if (!ids.includes(varName)) {
        imports.push(`import ${varName} from './${moduleName}';`);
        ids.push(varName);
    }
    body += imports.join('\n') + (imports.length ? '\n' : '');
    body += `export default [${ids.join(', ')}];\n`;
    writeFileSync(indexPath, body);
}

async function main() {
    const args = parseArgs(process.argv.slice(2));
    const source = readFileSync(args.file, 'utf8');
    const result = await parseExtension(source, { url: args.url || `file://${args.file}` });
    if (!result.ok) {
        console.error(`Failed to parse ${args.file}:`);
        console.error(JSON.stringify(result.errors, null, 2));
        process.exit(1);
    }
    const info = result.info;
    const id = info.id;
    if (!id) {
        console.error('Extension getInfo() is missing an "id".');
        process.exit(1);
    }
    const safeId = id.replace(/[^a-zA-Z0-9_-]/g, '_');
    const moduleName = `${safeId}.js`;
    mkdirSync(args.out, { recursive: true });
    const modPath = resolve(args.out, moduleName);
    const modBody =
        `// AUTO-GENERATED by scripts/extract-extension.mjs from ${basename(args.file)}.\n` +
        `// Do not edit by hand; re-run the extractor to regenerate.\n` +
        `const info = ${JSON.stringify(info, null, 2)};\n\n` +
        `export default info;\n`;
    writeFileSync(modPath, modBody);
    updateIndexFile(args.out, safeId, moduleName);
    console.log(`Registered extension "${id}" -> src/extensions/${moduleName}`);
    console.log(`Blocks: ${(info.blocks || []).map(b => b.opcode).join(', ')}`);
}

main().catch(err => {
    console.error(err);
    process.exit(1);
});
